-- Lets a signed-in user permanently delete their own account (required by the App Store
-- and Google Play for apps with sign-up). Deleting the auth user cascades to profiles,
-- user_progress, devices and entitlements.
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'not authenticated';
  end if;
  delete from auth.users where id = uid;
end;
$$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;
